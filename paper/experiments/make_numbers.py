"""Write paper/numbers.tex from the JSON results of the experiments.

    python paper/experiments/make_numbers.py

Every number quoted in the text of the paper is defined here, so that the
paper cannot drift from the experiments.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"


def fmt(n: int) -> str:
    return f"{n:,}".replace(",", "\\,")


def main() -> None:
    ver = json.loads((RES / "verification.json").read_text())
    run = json.loads((RES / "runtime.json").read_text())
    sim = json.loads((RES / "simplification.json").read_text())
    rws, can, seg = ver["rws"], ver["cancellation"], ver["segmentation"]
    curve = {c["threshold"]: c["minima"] for c in sim["curve"]}
    h_end = max(curve)
    plateau = [h for h, n in curve.items() if n == sim["wells"]]
    per_cell = [1e6 * (r["gradient_s"] + r["sequence_s"] + r["basins_s"]) / r["cells"]
                for r in run["rows"]]
    macros = {
        "nRWSimages": fmt(rws["images"]),
        "nRWScells": fmt(rws["cells"]),
        "nRWSdiff": fmt(rws["differences"]),
        "nCancelStacks": fmt(can["stacks"]),
        "nCancelPairs": fmt(can["pairs"]),
        "nCancelNotFlat": fmt(can["not_flat_for_F"]),
        "nCancelNotFlatPct": f"{100 * can['not_flat_for_F'] / can['pairs']:.0f}",
        "nMerges": fmt(can["min_saddle_merges"]),
        "nSeqs": fmt(seg["sequences"]),
        "nSeqCells": fmt(seg["cells"]),
        "nStrict": fmt(seg["existence_strictly_larger"]),
        "runtimeMachine": f"Python {run['python']}",
        "runtimeMinUs": f"{min(per_cell):.0f}",
        "runtimeMaxUs": f"{max(per_cell):.0f}",
        "runtimeMaxCells": fmt(max(r['cells'] for r in run['rows'])),
        "simplN": str(sim["size"]),
        "simplNoise": str(sim["noise"]),
        "simplWells": str(sim["wells"]),
        "simplMinStart": fmt(curve[0]),
        "simplHShow": str(sim["shown"]),
        "simplMinShow": fmt(curve[sim["shown"]]),
        "simplPlateauLo": str(min(plateau)),
        "simplPlateauHi": str(max(plateau)),
        "simplMinEnd": fmt(curve[h_end]),
        "simplHEnd": str(h_end),
        "simplCancel": fmt(sim["cancellations"]),
        "simplSeconds": f"{sim['seconds']:.0f}",
    }
    # the text states that the minima left are exactly the wells on an interval
    hs = sorted(curve)
    assert plateau and plateau == [h for h in hs if min(plateau) <= h <= max(plateau)]
    # the paper states that every check passed: refuse to write numbers otherwise
    assert rws["differences"] == 0
    assert can["flat_raised"] == can["flat_lowered"] == can["flooding"] == can["pairs"]
    assert can["acyclic"] == can["pairs"] and can["merge_ok"] == can["min_saddle_merges"]
    assert seg["closure_equals_scan"] == seg["sequences"]
    assert seg["bridges_equal_saddle_stable_sets"] == seg["sequences"]
    assert all(v is True for k, v in sim["checks"].items()
               if k in ("stack", "raised_only", "level_flat", "acyclic", "flooding"))
    lines = ["% generated by paper/experiments/make_numbers.py -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    (HERE.parent / "numbers.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
